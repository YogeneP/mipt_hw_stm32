int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_IWDG_Init();
  /* USER CODE BEGIN 2 */

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  uint32_t tick_led = 0;
  uint32_t tick_btn = 0;
  uint32_t blink_period = 200;

  if((HAL_GetTick() - tick_led) > 200) {
    LED_GPIO_Port->BSRR = (uint32_t)LED_Pin;
    tick_led = HAL_GetTick();
  } 
  if((HAL_GetTick() - tick_led) > 400) {
    LED_GPIO_Port->BSRR = (uint32_t)LED_Pin << 16;
    tick_led = HAL_GetTick();
  } 
  HAL_Delay(1000);

  uint32_t rcc_csr = RCC->CSR; 
  
  RCC->CSR = RCC_CSR_RMVF; //clear the flags
  (void)RCC->CSR; 

  if(rcc_csr & RCC_CSR_PINRSTF) { blink_period = 50; } // superfast blinker - PINRSTF is always up after reset - it goes first
  if(rcc_csr & RCC_CSR_IWDGRSTF) { blink_period = 200; } // fast blinker
  if(rcc_csr & RCC_CSR_BORRSTF) { blink_period = 500; } //  slow blinker
  if(rcc_csr & RCC_CSR_PORRSTF) { blink_period = 11000; } // keeps LED on (IWDG resets the MCU in 10s )
  if(rcc_csr & RCC_CSR_SFTRSTF) { blink_period = 0; } // keeps LED OFF

  while (1)
  {
    uint32_t tick = HAL_GetTick();

    if(blink_period) {
      if((tick - tick_led) > blink_period) {
        LED_GPIO_Port->BSRR = (uint32_t)LED_Pin << ((LED_GPIO_Port->ODR & LED_Pin) ? 16 : 0);
        tick_led = tick;
      } 
    } else {
      LED_GPIO_Port->BSRR = (uint32_t)LED_Pin;
    }

    if ((tick - tick_btn) > BTN_TICKS) {
      if ((BTN_GPIO_Port->IDR & BTN_Pin) == RESET) {
        NVIC_SystemReset();
      }
    }
  
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

